    def _compute_rotary(self, code: str, turns_edit: QtWidgets.QLineEdit) -> None:
        try:
            turns = int(turns_edit.text())
        except ValueError:
            self._set_status("Turns must be a whole integer.", "#ff4444")
            return
        if turns <= 0:
            self._set_status("Turns must be greater than zero.", "#ff4444")
            return
        self._send(f"CAL_{code} {turns}")

    def _apply_rotary(self, axis: str, save: bool) -> None:
        cal = self._state.last_theta if axis == "theta" else self._state.last_phi
        if cal is None:
            self._set_status(f"No {axis} trial computed yet.", "#ff4444")
            return
        self._start_ppr_apply(
            f"SET_PPR_ROTARY {cal.ppr:.2f}", save, f"PPR for {axis}",
        )

