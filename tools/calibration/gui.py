"""gui.py — standalone EVKA calibration app.

One full-screen window: connect, watch live position, run every calibration stage.

    python -m tools.calibration.gui                          # open disconnected
    python -m tools.calibration.gui --serial /dev/ttyUSB0
    python -m tools.calibration.gui --tcp 192.168.1.84:8080
    python -m tools.calibration.gui --ws 192.168.1.50

Tabs: Wire / Theta / Phi PPR trials, Endpoint (world<->sensor pairs, PASS/FAIL report,
gated deploy), Points, Commands.

This tool has no software zero on purpose: every captured coordinate is the raw sensor
frame straight off the wire. A display offset would be absorbed into the fit's translation
and silently produce a transform that is only valid while that offset is active.

The report itself is generated by tools/calibration/report.py — the same engine the CLI and
evka_gui use, so all three always agree on the verdict.
"""

