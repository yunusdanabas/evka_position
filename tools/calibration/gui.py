    # --------------------------------------------------------- session files
    def _load_session(self) -> None:
        """Populate the table from the session CSVs — they are the source of truth."""
        try:
            report.ensure_templates(self._session_dir)
            points: List[Tuple[str, report.PointPair]] = []
            for role, name in (
                (ROLE_CALIBRATION, report.CALIBRATION_CSV),
                (ROLE_VALIDATION, report.VALIDATION_CSV),
            ):
                for p in report.load_point_pairs(self._session_dir / name):
                    points.append((role, p))
        except (OSError, ValueError) as exc:
            self._set_status(f"Could not load session: {exc}", "#ff4444")
            return
        self._points = points
        self._refresh_endpoint_table()
        if points:
            self._set_status(f"Loaded {len(points)} points from {self._session_dir}.", "#888888")

    def _save_session(self) -> bool:
        """Rewrite both CSVs from current state.

        Whole-file rewrite keeps add/delete/role-change on one code path — no dirty tracking.
        """
        try:
            report.save_session_sets(
                self._session_dir,
                [p for role, p in self._points if role == ROLE_CALIBRATION],
                [p for role, p in self._points if role == ROLE_VALIDATION],
            )
        except OSError as exc:
            message = f"Could not save session: {exc}"
            self._load_session()
            self._set_status(message, "#ff4444")
            return False
        return True

    def _refresh_endpoint_table(self) -> None:
        self._ep_table.setRowCount(len(self._points))
        for row, (role, p) in enumerate(self._points):
            values = [p.label, *(f"{v:.2f}" for v in p.world), *(f"{v:.2f}" for v in p.sensor)]
            for col, text in enumerate(values):
                self._ep_table.setItem(row, col, QtWidgets.QTableWidgetItem(text))
            combo = QtWidgets.QComboBox()
            for r in (ROLE_CALIBRATION, ROLE_VALIDATION):
                combo.addItem(ROLE_LABELS[r], r)
            combo.setCurrentIndex(0 if role == ROLE_CALIBRATION else 1)
            combo.currentIndexChanged.connect(
                lambda _idx, r=row, c=combo: self._change_role(r, c.currentData())
            )
            self._ep_table.setCellWidget(row, 7, combo)
            self._ep_table.setItem(row, 8, QtWidgets.QTableWidgetItem(p.notes))

    def _change_role(self, row: int, role: str) -> None:
        if not 0 <= row < len(self._points):
            return
        old_role, pair = self._points[row]
        if old_role == role:
            return
        self._points[row] = (role, pair)
        if not self._save_session():
            return
        self._invalidate_report(f"Moved {pair.label} to {ROLE_LABELS[role]} set — regenerate.")

